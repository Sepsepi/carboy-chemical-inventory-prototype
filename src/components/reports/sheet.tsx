/** Page margins and page numbers on paper. Chrome 131+ draws the margin boxes. */
const PRINT_CSS = `
@media print {
  @page {
    size: letter;
    margin: 0.55in 0.5in 0.6in;
    @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 9px "IBM Plex Sans", sans-serif; }
  }
  [data-print="sheet"] { padding: 0 !important; }
  [data-print="sheet"] * { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
}`;

export function ReportSheet({ children, footer }: { children: React.ReactNode; footer: string }) {
  return (
    <article
      data-print="sheet"
      style={PAPER_TOKENS}
      className="mx-auto w-full max-w-[880px] min-w-0 rounded-sm border border-border-strong bg-card px-4 py-6 text-[12.5px] leading-[1.45] text-foreground sm:px-8 sm:py-9 md:px-11"
    >
      <style>{PRINT_CSS}</style>
      {children}
      <footer className="mt-8 flex flex-wrap justify-between gap-2 border-t border-border pt-2 text-[10.5px] text-muted-foreground">
        <span>{footer}</span>
        <span>Generated by Carboy from prototype data</span>
      </footer>
    </article>
  );
}

/** Title block: the form name on the left, the identifiers in a ruled box on the right. */
export function DocHeader({
  kicker,
  title,
  period,
  meta,
}: {
  kicker: string;
  title: string;
  period: string;
  meta: { label: string; value: React.ReactNode }[];
}) {
  return (
    <header className="flex flex-col gap-4 border-b-2 border-foreground pb-4 sm:flex-row sm:items-end sm:justify-between">
      <div className="min-w-0">
        <p className="text-[11px] text-muted-foreground">{kicker}</p>
        <h2 className="mt-1 max-w-[30ch] text-[19px] leading-tight font-semibold tracking-[-0.01em] text-foreground">
          {title}
        </h2>
        <p className="mt-1.5 text-[12.5px] text-foreground">{period}</p>
        <p className="mt-2 inline-flex items-center gap-1.5 rounded-sm border border-dashed border-border-strong px-1.5 py-0.5 text-[10.5px] text-muted-foreground">
          <span className="font-semibold text-foreground">Sample</span>
          Generated from prototype data. Not for filing.
        </p>
      </div>
      <dl className="grid shrink-0 grid-cols-2 border-t border-l border-border-strong text-[11px] sm:w-[260px]">
        {meta.map((m) => (
          <div key={m.label} className="min-w-0 border-r border-b border-border-strong px-2 py-1.5">
            <dt className="text-[10px] text-muted-foreground">{m.label}</dt>
            <dd className="mt-0.5 truncate font-medium text-foreground">{m.value}</dd>
          </div>
        ))}
      </dl>
    </header>
  );
}

/** A numbered part of the form. */
export function DocSection({
  number,
  of,
  title,
  note,
  children,
  className,
}: {
  number: number;
  of: number;
  title: string;
  note?: React.ReactNode;
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <section className={cn("mt-7", className)}>
      <div className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1 border-b border-foreground pb-1.5 break-after-avoid">
        <h3 className="text-[13.5px] font-semibold text-foreground">
          <span className="mr-2 tabular text-muted-foreground">Part {number}</span>
          {title}
        </h3>
        <span className="text-[10.5px] text-muted-foreground">
          Part {number} of {of}
        </span>
      </div>
      {note && <p className="mt-2 text-[11.5px] text-muted-foreground">{note}</p>}
      <div className="mt-3">{children}</div>
    </section>
  );
}

/** Ruled grid of form fields, like the boxes on a printed form. */
export function FormGrid({ children, className }: { children: React.ReactNode; className?: string }) {
  return (
    <dl className={cn("grid border-t border-l border-border-strong", className)}>{children}</dl>
  );
}

export function FormCell({
  label,
  children,
  className,
}: {
  label: string;
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <div className={cn("min-w-0 border-r border-b border-border-strong px-2.5 py-1.5", className)}>
      <dt className="text-[10.5px] text-muted-foreground">{label}</dt>
      <dd className="mt-0.5 text-[12.5px] break-words text-foreground">{children}</dd>
    </div>
  );
}

/** A table inside the sheet: scrolls sideways on narrow screens, flows on paper. */
export function SheetTable({
  head,
  children,
  minWidth = 560,
  className,
}: {
  head: { label: string; align?: "right" }[];
  children: React.ReactNode;
  minWidth?: number;
  className?: string;
}) {
  return (
    <div className={cn("scrollbar-thin overflow-x-auto print:overflow-visible", className)}>
      <table className="w-full border-collapse text-[12px]" style={{ minWidth }}>
        <thead>
          <tr className="border-y border-border-strong bg-subtle">
            {head.map((h) => (
              <th
                key={h.label}
                scope="col"
                className={cn(
                  "px-2 py-1.5 text-left text-[10.5px] font-medium whitespace-nowrap text-muted-foreground",
                  h.align === "right" && "text-right",
                )}
              >
                {h.label}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>{children}</tbody>
      </table>
    </div>
  );
}

